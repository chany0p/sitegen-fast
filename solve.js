// Fast drop-in for makefun-site 1.0.0 (site-generator-speed-01-run-20261122).
//
// Same answers as makefun-site's build, byte for byte, on every input; written
// for CPU time. The semantics follow vendor/makefun-site (README.md + lib/*)
// exactly; only the work is cheaper:
//  - HTML escaping scans once and copies plain runs whole (the reference
//    escapes one character at a time through a regex, per character).
//  - Markdown is lexed and rendered in one fused pass, with no token objects.
//  - slugify has an ASCII fast path (NFKD is the identity on ASCII) plus a
//    per-build cache (titles/tags repeat); non-ASCII takes the reference path.
//  - word counting and the link-target whitespace test use the exact JS \s
//    set, scanned by code unit, never a regex.
//  - Template rendering pushes fragments into one array instead of building
//    a string per node; includes/for/if share the same array.
//  - No value is cached from one case to the next: every per-build cache is
//    created fresh inside run().
//
// No dependency, no I/O, no clock, no randomness: the answer is a function
// of the input alone, as the reference is.

